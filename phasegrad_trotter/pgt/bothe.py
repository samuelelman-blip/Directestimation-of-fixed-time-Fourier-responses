_K = (2 * math.sqrt(2 * math.e ** 3) / 3) ** (2 / 3)


def fold(theta: float) -> float:
    """theta mapped by Cliffords to [0, pi/8], as in their script."""
    if abs(theta) > math.pi / 8:
        theta = (theta + math.pi / 8) % (math.pi / 4) - math.pi / 8
    return abs(theta)


def small_angle(theta: float, delta: float) -> float:
    """Expected T count with the identity as under-rotation: the staircase where it applies,
    else the asymptotic formula (Appendix A of arXiv:2605.31544, before its final minimum)."""
    theta = fold(theta)
    if theta == 0:
        return 0.0
    tanalpha = delta / math.sin(2 * theta) + math.tan(theta)
    i = bisect.bisect_right(_TANALPHA_R, tanalpha) - 1
    if i >= 0 and math.tan(theta) <= _PHI_R[i]:
        return _AVG_T_R[i] * math.sin(2 * theta)
    alpha = delta / (2 * theta) + theta
    phi0 = max(alpha - alpha / math.log(_K / alpha), theta)
    return (3 * theta / (alpha + 2 * phi0)) * math.log2(
        12 / (((alpha - phi0) ** 2) * (alpha + 2 * phi0)))


def mixed_diagonal(delta: float) -> float:
    return 1.52 * math.log2(1 / delta) - 0.01


def mixed_fallback(delta: float) -> float:
    return 0.53 * math.log2(1 / delta) + 4.86


def t_ancilla_free(theta: float, delta: float) -> float:
    """Eq. (12): the angle-dependent ancilla-free cost."""
    return min(small_angle(theta, delta), mixed_diagonal(delta))


def t_fallback(theta: float, delta: float) -> float:
    """Eq. (15): the angle-dependent fallback cost, the cheaper of their two schemes."""
    return min(small_angle(theta, 2 * delta), mixed_fallback(delta))
